/**
 * 將原始文字轉換為 TTS 發音校正版本
 */
export function fixPronunciation(text: string): string {
  let result = text

  // 按照詞彙長度排序（長的先替換，避免短詞覆蓋長詞的一部分）
  const sortedKeys = Object.keys(pronunciationMap).sort((a, b) => b.length - a.length)

  for (const original of sortedKeys) {
    const replacement = pronunciationMap[original]
    result = result.split(original).join(replacement)
  }

  return result
}
